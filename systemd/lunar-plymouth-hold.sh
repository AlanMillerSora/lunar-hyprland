#!/bin/sh
# ════════════════════════════════════════════════════════════════
#  lunar-plymouth-hold.sh — держим заставку до экрана входа.
#
#  Штатный plymouth-quit гасит Plymouth сразу после multi-user,
#  а SDDM (у нас на Xorg) поднимает greeter ещё ~1-2 секунды.
#  Из-за этого лого только мелькало.
#
#  Этот скрипт ждёт появления процесса sddm-greeter (окно входа)
#  и только потом просит Plymouth уйти. Лимит — чтобы при сбое
#  входа не залипнуть навсегда (TTY/аварийный вход остаются).
# ════════════════════════════════════════════════════════════════
set -u

LIMIT=60          # 60 * 0.1 c = максимум 6 секунд ожидания
i=0

while [ "$i" -lt "$LIMIT" ]; do
  if pgrep -x sddm-greeter >/dev/null 2>&1; then
    break
  fi
  # если Plymouth уже не работает — выходим, ждать нечего
  if ! pgrep -x plymouthd >/dev/null 2>&1; then
    exit 0
  fi
  sleep 0.1
  i=$((i + 1))
done

# логотип ещё мгновение виден под уже готовым экраном входа
sleep 0.3
plymouth quit >/dev/null 2>&1 || true

exit 0
